from __future__ import annotations

import argparse
import csv
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


AXES = ("x", "y", "z")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Plot estimated force and ground-truth force time-series from a staged-direction-force CSV log."
    )
    parser.add_argument(
        "csv_path",
        type=Path,
        help="Path to the CSV generated by staged_direction_force_eval.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Optional output image path. Defaults to <csv_stem>_force_timeseries.png next to the CSV.",
    )
    parser.add_argument(
        "--prefixes",
        nargs="+",
        default=None,
        help="Optional force groups to plot, for example: gripper base. Defaults to auto-detected groups.",
    )
    parser.add_argument(
        "--active-only",
        action="store_true",
        help="Only keep samples where the target force norm is non-zero.",
    )
    parser.add_argument(
        "--title",
        type=str,
        default=None,
        help="Optional custom figure title.",
    )
    return parser


def parse_float(value: str) -> float:
    text = value.strip()
    if not text:
        return float("nan")
    try:
        return float(text)
    except ValueError as exc:
        raise ValueError(f"Failed to parse float value: {value!r}") from exc


def load_csv_rows(csv_path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with csv_path.open("r", newline="") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames is None:
            raise ValueError(f"CSV has no header: {csv_path}")
        rows = list(reader)
    if not rows:
        raise ValueError(f"CSV has no data rows: {csv_path}")
    return list(reader.fieldnames), rows


def detect_prefixes(fieldnames: list[str]) -> list[str]:
    prefixes: list[str] = []
    suffix = "_force_est_local_x"
    for name in fieldnames:
        if name.endswith(suffix):
            prefixes.append(name[: -len(suffix)])
    return prefixes


def validate_prefixes(fieldnames: list[str], prefixes: list[str]) -> list[str]:
    missing_columns: list[str] = []
    valid_prefixes: list[str] = []
    for prefix in prefixes:
        required = [
            f"{prefix}_force_est_local_{axis}" for axis in AXES
        ] + [
            f"{prefix}_force_tgt_local_{axis}" for axis in AXES
        ] + [
            f"{prefix}_force_err_l2"
        ]
        if all(name in fieldnames for name in required):
            valid_prefixes.append(prefix)
        else:
            missing_columns.extend([name for name in required if name not in fieldnames])
    if not valid_prefixes:
        raise ValueError(
            "No valid force prefixes found. Missing columns: " + ", ".join(sorted(set(missing_columns)))
        )
    return valid_prefixes


def build_series(rows: list[dict[str, str]], prefixes: list[str]) -> dict[str, np.ndarray | dict[str, np.ndarray]]:
    time_s = np.asarray([parse_float(row["time_s"]) for row in rows], dtype=np.float64)
    series: dict[str, np.ndarray | dict[str, np.ndarray]] = {"time_s": time_s}
    for prefix in prefixes:
        est = np.asarray(
            [[parse_float(row[f"{prefix}_force_est_local_{axis}"]) for axis in AXES] for row in rows],
            dtype=np.float64,
        )
        tgt = np.asarray(
            [[parse_float(row[f"{prefix}_force_tgt_local_{axis}"]) for axis in AXES] for row in rows],
            dtype=np.float64,
        )
        err_l2 = np.asarray([parse_float(row[f"{prefix}_force_err_l2"]) for row in rows], dtype=np.float64)
        series[prefix] = {
            "est": est,
            "tgt": tgt,
            "err_l2": err_l2,
        }
    return series


def filter_active_samples(series: dict[str, np.ndarray | dict[str, np.ndarray]], prefixes: list[str]) -> dict[str, np.ndarray | dict[str, np.ndarray]]:
    masks = []
    for prefix in prefixes:
        prefix_data = series[prefix]
        assert isinstance(prefix_data, dict)
        tgt = np.asarray(prefix_data["tgt"], dtype=np.float64)
        masks.append(np.linalg.norm(tgt, axis=1) > 1e-9)
    active_mask = np.logical_or.reduce(masks)
    if not np.any(active_mask):
        raise ValueError("No active-force samples found after applying --active-only.")

    filtered: dict[str, np.ndarray | dict[str, np.ndarray]] = {
        "time_s": np.asarray(series["time_s"])[active_mask],
    }
    for prefix in prefixes:
        prefix_data = series[prefix]
        assert isinstance(prefix_data, dict)
        filtered[prefix] = {
            key: np.asarray(value)[active_mask] for key, value in prefix_data.items()
        }
    return filtered


def plot_series(
    series: dict[str, np.ndarray | dict[str, np.ndarray]],
    prefixes: list[str],
    output_path: Path,
    title: str,
) -> None:
    time_s = np.asarray(series["time_s"], dtype=np.float64)
    nrows = 4
    ncols = len(prefixes)
    fig, axes = plt.subplots(nrows=nrows, ncols=ncols, figsize=(7.5 * ncols, 12.0), sharex=True)
    axes = np.asarray(axes, dtype=object)
    if axes.ndim == 1:
        axes = axes[:, None]

    for col, prefix in enumerate(prefixes):
        prefix_data = series[prefix]
        assert isinstance(prefix_data, dict)
        est = np.asarray(prefix_data["est"], dtype=np.float64)
        tgt = np.asarray(prefix_data["tgt"], dtype=np.float64)
        err_l2 = np.asarray(prefix_data["err_l2"], dtype=np.float64)
        axis_err = est - tgt

        for row, axis_name in enumerate(AXES):
            ax = axes[row, col]
            axis_idx = AXES.index(axis_name)
            ax.plot(time_s, est[:, axis_idx], label="estimate", linewidth=1.4, color="tab:blue")
            ax.plot(time_s, tgt[:, axis_idx], label="ground truth", linewidth=1.2, color="tab:orange", alpha=0.9)
            ax.set_ylabel(f"{axis_name.upper()} force [N]")
            ax.set_title(f"{prefix} force ({axis_name.upper()})")
            ax.grid(True, linestyle="--", alpha=0.35)
            if row == 0:
                ax.legend(loc="upper right")

        err_ax = axes[3, col]
        err_ax.plot(time_s, err_l2, label="L2 error", linewidth=1.3, color="tab:red")
        if prefix == "base":
            err_ax.axhline(0.0, color="black", linewidth=0.8, linestyle=":", alpha=0.6)
            for axis_idx, axis_name in enumerate(AXES):
                err_ax.plot(
                    time_s,
                    axis_err[:, axis_idx],
                    label=f"{axis_name.upper()} error",
                    linewidth=1.1,
                    alpha=0.9,
                )
        err_ax.set_ylabel("L2 error [N]")
        if prefix == "base":
            err_ax.set_title(f"{prefix} force error (L2 + axis-wise)")
        else:
            err_ax.set_title(f"{prefix} force error")
        err_ax.grid(True, linestyle="--", alpha=0.35)
        err_ax.set_xlabel("time [s]")
        err_ax.legend(loc="upper right")

    fig.suptitle(title)
    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=200, bbox_inches="tight")
    plt.close(fig)


def resolve_output_path(csv_path: Path, output_path: Path | None) -> Path:
    if output_path is not None:
        return output_path
    return csv_path.with_name(f"{csv_path.stem}_force_timeseries.png")


def main() -> int:
    args = build_parser().parse_args()
    csv_path = args.csv_path.resolve()
    fieldnames, rows = load_csv_rows(csv_path)

    prefixes = args.prefixes if args.prefixes is not None else detect_prefixes(fieldnames)
    prefixes = validate_prefixes(fieldnames, prefixes)

    series = build_series(rows, prefixes)
    if args.active_only:
        series = filter_active_samples(series, prefixes)

    output_path = resolve_output_path(csv_path, args.output)
    title = args.title or f"Force estimate vs ground truth\n{csv_path.name}"
    plot_series(series, prefixes, output_path, title)

    print(f"Saved figure to: {output_path}")
    print(f"Plotted prefixes: {', '.join(prefixes)}")
    if args.active_only:
        print("Filtered to active-force samples only.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
